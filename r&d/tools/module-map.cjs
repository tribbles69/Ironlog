#!/usr/bin/env node
/* The module split's map and its mover (r&d/notes/module-split.md).

   Reads the app's script — the inline <script> blocks of index.html while
   that is where the code is, js/*.js once it has moved — and works out, for
   every top-level statement, which other top-level names it reads and writes.
   Scopes are resolved properly (params, locals, block scope, catch, named
   function expressions), because the import lists are generated from this: a
   read it misses is an import that isn't there, and a ReferenceError the
   first time that line runs.

   Needs the TypeScript parser, which this repo does not depend on:
     NODE_PATH=../slew-v2/node_modules node "r&d/tools/module-map.cjs" [mode]

   Modes
     (none)               summary: units, statements, load-time reads across units
     --outline            every top-level statement, one line each
     --deps <name>        who reads and writes one top-level name
     --plan <file.json>   roll up by line ranges [{ module, ranges: [[a, b]] }] (index.html only)
     --json <out.json>    with --plan or on js/: exports and imports per module
     --make-assign <plan.json> <out.json>
                          turn line ranges into a name → module table, which
                          survives lines moving
     --move <module>      cut every statement assigned to <module> out of
                          js/app.js into js/<module>.js, then --sync
     --sync               regenerate, in every js/*.js: `export` on each
                          declaration another file (or the smoke test) uses,
                          setters for variables assigned from another file,
                          and the import block at the top
     --check              exit 1 if --sync would change anything, or a name is
                          declared twice
*/
const fs = require('fs'), path = require('path'), crypto = require('crypto');
let ts;
try { ts = require('typescript'); } catch (e) {
  console.error('typescript not found — run with NODE_PATH=../slew-v2/node_modules'); process.exit(1);
}
const ROOT = path.resolve(__dirname, '..', '..');
const JS = path.join(ROOT, 'js');
const ASSIGN = path.join(ROOT, 'r&d/notes/module-split-assign.json');
const arg = (k, n = 1) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + n] : null; };
const has = k => process.argv.includes(k);
const SK = ts.SyntaxKind;
const IMPORT_HEAD = '/* imports — generated by r&d/tools/module-map.cjs --sync, not by hand */';
const IMPORT_TAIL = '/* end imports */';
/* Names the page-side test tools reach for; they stay exported even when no
   module needs them. */
const TOOL_FILES = ['r&d/tools/smoke.js', 'r&d/tools/baseline.js'];
/* Variables the smoke test assigns to directly: they need a setter from the start. */
const TOOL_SETTERS = ['cardioWhyLast'];
const SETTER_NAME = { S: 'setState' };
const setterFor = n => SETTER_NAME[n] || 'set' + n.replace(/^_*/, '').replace(/^./, c => c.toUpperCase());

/* ---------- units ---------- */
function loadUnits() {
  const units = [];
  if (fs.existsSync(JS)) for (const f of fs.readdirSync(JS).filter(f => f.endsWith('.js')).sort()) {
    units.push({ name: f.replace(/\.js$/, ''), file: path.join(JS, f), text: fs.readFileSync(path.join(JS, f), 'utf8'), module: true });
  }
  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  let bi = 0;
  for (const m of html.matchAll(/<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g)) {
    const start = m.index + m[0].indexOf('>') + 1;
    const line = html.slice(0, start).split('\n').length;
    units.push({ name: 'index.html#' + (++bi), file: null, text: '\n'.repeat(line - 1) + m[1], module: false, inline: true });
  }
  return units;
}

function bindingNames(name, out) {
  if (ts.isIdentifier(name)) out.push(name.text);
  else for (const el of name.elements) if (!ts.isOmittedExpression(el)) bindingNames(el.name, out);
  return out;
}
const isFnLike = n => ts.isFunctionDeclaration(n) || ts.isFunctionExpression(n) || ts.isArrowFunction(n) || ts.isMethodDeclaration(n) || ts.isGetAccessor(n) || ts.isSetAccessor(n) || ts.isConstructorDeclaration(n);

function parseUnit(u) {
  const sf = u.sf = ts.createSourceFile(u.name + '.js', u.text, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  u.stmts = [];
  /* A file's opening comment belongs to the file, not to its first statement. */
  const opening = u.module ? (u.text.match(/^(\s*\/\*[\s\S]*?\*\/[ \t]*\n)/) || [''])[0] : '';
  let prevEnd = opening.length;
  for (const node of sf.statements) {
    const s = { unit: u, node, names: [], declKind: '', kind: SK[node.kind] };
    s.generated = ts.isImportDeclaration(node) || ts.isExportDeclaration(node);
    s.exported = !!(node.modifiers && node.modifiers.some(m => m.kind === SK.ExportKeyword));
    if (ts.isFunctionDeclaration(node) || ts.isClassDeclaration(node)) { s.names.push(node.name.text); s.declKind = ts.isClassDeclaration(node) ? 'class' : 'function'; }
    else if (ts.isVariableStatement(node)) {
      s.declKind = node.declarationList.flags & ts.NodeFlags.Const ? 'const' : node.declarationList.flags & ts.NodeFlags.Let ? 'let' : 'var';
      for (const d of node.declarationList.declarations) bindingNames(d.name, s.names);
    }
    s.start = node.getStart(sf); s.end = node.end;
    s.line = sf.getLineAndCharacterOfPosition(s.start).line + 1;
    s.lineEnd = sf.getLineAndCharacterOfPosition(s.end).line + 1;
    s.bytes = s.end - s.start;
    /* The segment a statement owns in the file: from the end of the previous
       one's segment (so its leading comments travel with it) to the end of
       its own line, taking a trailing comment on that line with it. */
    let e = s.end; const t = u.text;
    const ws = () => { while (t[e] === ' ' || t[e] === '\t') e++; };
    ws();
    if (t.startsWith('//', e)) { while (e < t.length && t[e] !== '\n') e++; }
    else if (t.startsWith('/*', e)) { const c = t.indexOf('*/', e); const nl = t.indexOf('\n', e); if (c >= 0 && (nl < 0 || c < nl)) { const save = e; e = c + 2; ws(); if (e < t.length && t[e] !== '\n' && t[e] !== '\r') e = save; } }
    if (t[e] === '\r') e++;
    if (t[e] === '\n') e++; else if (e < t.length) e = s.end;   // more code on the line: leave it
    s.segStart = prevEnd; s.segEnd = e; prevEnd = e;
    s.hash = crypto.createHash('sha1').update(t.slice(s.start, s.end)).digest('hex').slice(0, 12);
    u.stmts.push(s);
  }
  u.tail = prevEnd;
}

/* ---------- scope-accurate free references ---------- */
function varsOf(fn) {   // `var` names of a function body, not entering nested functions
  const out = new Set();
  (function walk(n) {
    if (n !== fn && isFnLike(n)) return;
    if (ts.isVariableDeclarationList(n) && !(n.flags & (ts.NodeFlags.Let | ts.NodeFlags.Const))) for (const d of n.declarations) bindingNames(d.name, []).forEach(x => out.add(x));
    ts.forEachChild(n, walk);
  })(fn);
  return out;
}
function lexicalOf(statements) {   // let/const/class/function declared directly in a statement list
  const out = new Set();
  for (const st of statements) {
    if (ts.isVariableStatement(st) && (st.declarationList.flags & (ts.NodeFlags.Let | ts.NodeFlags.Const))) for (const d of st.declarationList.declarations) bindingNames(d.name, []).forEach(x => out.add(x));
    else if ((ts.isFunctionDeclaration(st) || ts.isClassDeclaration(st)) && st.name) out.add(st.name.text);
  }
  return out;
}
function refsOf(top, isTopName) {
  const refs = [];   // { name, node, write, assign (BinaryExpression of a plain `x = …`), eager }
  const scopes = [];
  const local = name => scopes.some(s => s.has(name));
  function ident(n, parent, fnDepth) {
    const name = n.text;
    if (parent) {
      if (ts.isPropertyAccessExpression(parent) && parent.name === n) return;
      if (ts.isQualifiedName(parent)) return;
      if ((ts.isPropertyAssignment(parent) || ts.isMethodDeclaration(parent) || ts.isPropertyDeclaration(parent) || ts.isGetAccessor(parent) || ts.isSetAccessor(parent) || ts.isEnumMember(parent)) && parent.name === n) return;
      if (ts.isBindingElement(parent) && (parent.propertyName === n || parent.name === n)) return;
      if ((ts.isVariableDeclaration(parent) || ts.isParameter(parent) || ts.isFunctionDeclaration(parent) || ts.isFunctionExpression(parent) || ts.isClassDeclaration(parent) || ts.isClassExpression(parent)) && parent.name === n) return;
      if (ts.isLabeledStatement(parent) || ts.isBreakStatement(parent) || ts.isContinueStatement(parent)) return;
      if (ts.isImportSpecifier(parent) || ts.isExportSpecifier(parent) || ts.isImportClause(parent) || ts.isNamespaceImport(parent) || ts.isMetaProperty(parent)) return;
    }
    if (local(name) || !isTopName(name)) return;
    let write = false, assign = null;
    if (parent) {
      if (ts.isBinaryExpression(parent) && parent.left === n && parent.operatorToken.kind >= SK.FirstAssignment && parent.operatorToken.kind <= SK.LastAssignment) { write = true; if (parent.operatorToken.kind === SK.EqualsToken) assign = parent; }
      if ((ts.isPrefixUnaryExpression(parent) || ts.isPostfixUnaryExpression(parent)) && (parent.operator === SK.PlusPlusToken || parent.operator === SK.MinusMinusToken)) write = true;
      if ((ts.isForInStatement(parent) || ts.isForOfStatement(parent)) && parent.initializer === n) write = true;
      let p = parent, c = n;   // [a, b] = …, ({ a } = …)
      while (p && (ts.isArrayLiteralExpression(p) || ts.isObjectLiteralExpression(p) || ts.isShorthandPropertyAssignment(p) || (ts.isPropertyAssignment(p) && p.initializer === c) || ts.isSpreadElement(p) || ts.isSpreadAssignment(p) || ts.isParenthesizedExpression(p))) { c = p; p = p.parent; }
      if (p && p !== parent && ts.isBinaryExpression(p) && p.left === c && p.operatorToken.kind === SK.EqualsToken) write = true;
    }
    refs.push({ name, node: n, write, assign, eager: fnDepth === 0 });
  }
  function walk(n, parent, fnDepth) {
    if (ts.isIdentifier(n)) return ident(n, parent, fnDepth);
    let pushed = 0;
    const push = set => { scopes.push(set); pushed++; };
    if (isFnLike(n)) {
      const s = new Set(['arguments']);
      for (const p of n.parameters) bindingNames(p.name, []).forEach(x => s.add(x));
      if (ts.isFunctionExpression(n) && n.name) s.add(n.name.text);
      if (n.body) { varsOf(n).forEach(x => s.add(x)); if (ts.isBlock(n.body)) lexicalOf(n.body.statements).forEach(x => s.add(x)); }
      push(s);
      /* the top statement itself, when it is a function declaration, is not "nested" */
      const depth = n === top ? fnDepth : fnDepth + 1;
      ts.forEachChild(n, c => walk(c, n, c === n.body || n.parameters.includes(c) ? depth : fnDepth));
      scopes.length -= pushed; return;
    }
    if (ts.isClassExpression(n) && n.name) push(new Set([n.name.text]));
    if (ts.isBlock(n) && !(parent && isFnLike(parent))) push(lexicalOf(n.statements));
    if (ts.isCaseBlock(n)) push(lexicalOf(n.clauses.flatMap(c => [...c.statements])));
    if (ts.isCatchClause(n) && n.variableDeclaration) push(new Set(bindingNames(n.variableDeclaration.name, [])));
    if ((ts.isForStatement(n) || ts.isForInStatement(n) || ts.isForOfStatement(n)) && n.initializer && ts.isVariableDeclarationList(n.initializer)) {
      push(new Set(n.initializer.declarations.flatMap(d => bindingNames(d.name, []))));
    }
    ts.forEachChild(n, c => walk(c, n, fnDepth));
    scopes.length -= pushed;
  }
  walk(top, null, 0);
  return refs;
}

function analyse(units) {
  units.forEach(parseUnit);
  const decl = new Map(), dups = [];
  for (const u of units) for (const s of u.stmts) for (const n of s.names) {
    if (decl.has(n)) dups.push(`${n}: ${decl.get(n).unit.name}:${decl.get(n).line} and ${u.name}:${s.line}`);
    decl.set(n, s);
  }
  /* a `var` at function scope hoisted out of a top-level block would be a global too; none exist, and lint-scope would say */
  for (const u of units) for (const s of u.stmts) {
    if (s.generated) { s.refs = []; continue; }
    s.refs = refsOf(s.node, n => decl.has(n)).filter(r => !(s.names.includes(r.name) && !r.write && decl.get(r.name) === s && !isFnLike(s.node) && false));
  }
  return { decl, dups };
}

/* ---------- editing ---------- */
function applyEdits(text, edits) {   // [{ start, end, text }], non-overlapping
  edits.sort((a, b) => b.start - a.start);
  for (let i = 1; i < edits.length; i++) if (edits[i].end > edits[i - 1].start) throw new Error('overlapping edits at ' + edits[i].start);
  for (const e of edits) text = text.slice(0, e.start) + e.text + text.slice(e.end);
  return text;
}
function toolNames(decl) {
  const out = new Set();
  for (const f of TOOL_FILES) {
    const p = path.join(ROOT, f); if (!fs.existsSync(p)) continue;
    for (const m of fs.readFileSync(p, 'utf8').matchAll(/[A-Za-z_$][\w$]*/g)) if (decl.has(m[0])) out.add(m[0]);
  }
  return out;
}
function importBlock(u, decl) {
  const from = new Map();
  for (const s of u.stmts) for (const r of s.refs) {
    const t = decl.get(r.name);
    if (t.unit === u || !t.unit.module) continue;   // a classic inline script's names are page globals
    (from.get(t.unit.name) || from.set(t.unit.name, new Set()).get(t.unit.name)).add(r.name);
  }
  if (!from.size) return '';
  const lines = [IMPORT_HEAD];
  for (const m of [...from.keys()].sort()) {
    const names = [...from.get(m)].sort();
    let cur = 'import {', body = [];
    for (const n of names) { if ((cur + ' ' + n + ',').length > 118) { body.push(cur); cur = ' '; } cur += ' ' + n + ','; }
    body.push(cur.replace(/,$/, ''));
    lines.push(body.join('\n') + ` } from './${m}.js';`);
  }
  lines.push(IMPORT_TAIL);
  return lines.join('\n') + '\n';
}
function stripImportBlock(text) {
  const a = text.indexOf(IMPORT_HEAD); if (a < 0) return text;
  const b = text.indexOf(IMPORT_TAIL, a); if (b < 0) throw new Error('import block has no end marker');
  let e = b + IMPORT_TAIL.length; if (text[e] === '\n') e++;
  return text.slice(0, a) + text.slice(e);
}

/* One pass of sync over the js/ files. Returns true if anything was written. */
function syncOnce(write) {
  let units = loadUnits().filter(u => u.module || u.inline);
  let { decl, dups } = analyse(units);
  if (dups.length) throw new Error('declared twice:\n  ' + dups.join('\n  '));
  const mods = units.filter(u => u.module);
  let changed = false;

  /* 1. assignments to another file's variable → setter calls, and the setters */
  const needSetter = new Map();   // name -> owning stmt
  const edits = new Map(mods.map(u => [u, []]));
  for (const n of TOOL_SETTERS) if (decl.has(n) && decl.get(n).unit.module && !decl.has(setterFor(n))) needSetter.set(n, decl.get(n));
  for (const u of mods) for (const s of u.stmts) for (const r of s.refs) {
    if (!r.write) continue;
    const t = decl.get(r.name);
    if (t.unit === u) continue;
    if (!t.unit.module) throw new Error(`${u.name}:${s.line} assigns ${r.name}, which an inline script declares`);
    if (!r.assign) throw new Error(`${u.name}:${s.line} writes ${r.name} (${t.unit.name}) with something other than a plain "=" — do this one by hand`);
    const rhs = r.assign.right;
    edits.get(u).push({ start: r.assign.getStart(u.sf), end: rhs.getStart(u.sf), text: setterFor(r.name) + '(' }, { start: rhs.end, end: rhs.end, text: ')' });
    if (!decl.has(setterFor(r.name))) needSetter.set(r.name, t);
  }
  for (const [n, t] of needSetter) {
    if (t.declKind !== 'let' && t.declKind !== 'var') throw new Error(`${n} is assigned from another file but is a ${t.declKind}`);
    edits.get(t.unit).push({ start: t.segEnd, end: t.segEnd, text: `export function ${setterFor(n)}(v) { return ${n} = v; }   // ${n} is assigned from another module; an import is read-only\n` });
  }
  for (const u of mods) if (edits.get(u).length) { changed = true; if (write) fs.writeFileSync(u.file, applyEdits(u.text, edits.get(u))); }
  if (changed) return write ? true : 'setters';

  /* 2. export what another file, or a test tool, uses */
  const tools = toolNames(decl);
  const want = new Set(tools);
  for (const u of mods) for (const s of u.stmts) for (const r of s.refs) if (decl.get(r.name).unit !== u) want.add(r.name);
  for (const u of mods) {
    const ed = [];
    for (const s of u.stmts) if (!s.exported && s.names.some(n => want.has(n))) ed.push({ start: s.start, end: s.start, text: 'export ' });
    if (ed.length) { changed = true; if (write) fs.writeFileSync(u.file, applyEdits(u.text, ed)); }
  }
  if (changed) return write ? true : 'exports';

  /* 3. the import block */
  for (const u of mods) {
    const body = stripImportBlock(u.text);
    const block = importBlock(u, decl);
    /* after the file's opening comment, if it starts with one */
    let at = 0;
    const m = body.match(/^(\s*\/\*[\s\S]*?\*\/[ \t]*\n)/);
    if (m && !m[1].includes(IMPORT_HEAD)) at = m[1].length;
    const next = body.slice(0, at) + block + body.slice(at);
    if (next !== u.text) { changed = true; if (write) fs.writeFileSync(u.file, next); }
  }
  return changed ? (write ? true : 'imports') : false;
}
function sync() { let n = 0; while (syncOnce(true)) if (++n > 8) throw new Error('sync does not settle'); return n; }

function move(mod) {
  const assign = JSON.parse(fs.readFileSync(ASSIGN, 'utf8'));
  /* the generated import block would otherwise ride along as the first statement's leading comment; sync writes it back */
  const appFile = path.join(JS, 'app.js');
  if (!fs.existsSync(appFile)) throw new Error('js/app.js not found');
  fs.writeFileSync(appFile, stripImportBlock(fs.readFileSync(appFile, 'utf8')));
  const units = loadUnits().filter(u => u.module);
  analyse(units);
  const app = units.find(u => u.name === 'app');
  const target = path.join(JS, mod + '.js');
  const of = s => s.names.length ? assign.names[s.names[0]] : (assign.anon[s.hash] || {}).module;
  const take = app.stmts.filter(s => !s.generated && of(s) === mod);
  if (!take.length) throw new Error(`nothing in js/app.js is assigned to ${mod}`);
  for (const s of take) for (const n of s.names) if (assign.names[n] !== mod) throw new Error(`${n} shares a statement with ${s.names[0]} but is assigned to ${assign.names[n]}`);
  const moved = take.map(s => app.text.slice(s.segStart, s.segEnd)).join('');
  const rest = applyEdits(app.text, take.map(s => ({ start: s.segStart, end: s.segEnd, text: '' })));
  const head = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : `/* Ironlog — ${assign.titles[mod] || mod}. Split out of index.html (r&d/notes/module-split.md). */\n`;
  fs.writeFileSync(target, head + moved.replace(/^\n+/, '\n'));
  fs.writeFileSync(app.file, rest);
  const n = sync();
  console.log(`moved ${take.length} statements (${(moved.length / 1024).toFixed(0)} kB) to js/${mod}.js; sync took ${n} pass(es)`);
}

/* ---------- reports ---------- */
function report() {
  const units = loadUnits();
  const live = units.filter(u => u.module || u.inline);
  const { decl, dups } = analyse(live);
  const stmts = live.flatMap(u => u.stmts).filter(s => !s.generated);
  const label = s => s.names.length ? `${s.declKind} ${s.names.slice(0, 6).join(', ')}${s.names.length > 6 ? ` … (+${s.names.length - 6})` : ''}` : `[${s.kind}] ${s.node.getText(s.unit.sf).slice(0, 70).replace(/\s+/g, ' ')}`;

  if (has('--outline')) for (const s of stmts) console.log(`${s.unit.name.padEnd(12)} ${String(s.line).padStart(5)}-${String(s.lineEnd).padEnd(5)} ${String(s.bytes).padStart(7)}  ${label(s)}`);

  if (arg('--deps')) {
    const name = arg('--deps'), d = decl.get(name);
    if (!d) { console.error('no such top-level name'); process.exit(1); }
    console.log(`${name}: ${d.declKind}, ${d.unit.name}:${d.line}`);
    const who = w => stmts.filter(s => s.refs.some(r => r.name === name && r.write === w)).map(s => `${s.unit.name}:${s.line} ${s.names[0] || '[' + s.kind + ']'}`);
    console.log(`written by ${who(true).length}:\n  ` + who(true).join('\n  '));
    console.log(`read by ${who(false).length}:\n  ` + who(false).slice(0, 300).join('\n  '));
  }

  /* which module a statement belongs to: a plan's line ranges, else its file */
  let modOf = s => s.unit.name;
  if (arg('--plan')) {
    const plan = JSON.parse(fs.readFileSync(arg('--plan'), 'utf8'));
    modOf = s => { for (const m of plan) for (const [a, b] of m.ranges) if (s.line >= a && s.line <= b) return m.module; return '(unassigned)'; };
  }
  stmts.forEach(s => { s.module = modOf(s); });

  if (arg('--make-assign')) {
    const out = { note: 'Which module each top-level statement of the app belongs to. Made from module-split-plan.json at 54ce89b by module-map.cjs --make-assign; edit by hand to move a name.', titles: {
      core: 'helpers everything uses', database: 'storage, sync and migrations', exercises: 'the exercise library, leaf model, demos and modifiers', stats: 'standards, records, weekly sets, the muscle map and the Stats page',
      events: 'meets, tests and run-in blocks', tools: 'the Tools sheet, report, calculators and the AI key', health: 'health, mobility, fitting test, vitals, cardio and body comp', vbt: 'bar speed: Measure, bar path, the load-velocity profile',
      coach: 'the coach', workout: 'calendar, Train, programs, autoregulation and the rest timer', ui: 'toast, modal, charts, router, Home, Settings and the Windows 98 skin', main: 'boot', data: 'bundled data' }, names: {}, anon: {} };
    for (const s of stmts) { if (s.names.length) s.names.forEach(n => { out.names[n] = s.module; }); else out.anon[s.hash] = { module: s.module, line: s.line, head: s.node.getText(s.unit.sf).slice(0, 60).replace(/\s+/g, ' ') }; }
    fs.writeFileSync(arg('--make-assign', 2), JSON.stringify(out, null, 1) + '\n');
    console.log(`assigned ${Object.keys(out.names).length} names and ${Object.keys(out.anon).length} unnamed statements`);
  }

  const mods = [...new Set(stmts.map(s => s.module))];
  const info = Object.fromEntries(mods.map(m => [m, { bytes: 0, stmts: 0, names: 0, exports: new Set(), imports: {}, writesIn: {} }]));
  for (const s of stmts) {
    const I = info[s.module]; I.bytes += s.bytes; I.stmts++; I.names += s.names.length;
    for (const r of s.refs) {
      const t = decl.get(r.name);
      if (t.module === s.module) continue;
      info[t.module].exports.add(r.name);
      (I.imports[t.module] = I.imports[t.module] || new Set()).add(r.name);
      if (r.write) (info[t.module].writesIn[r.name] = info[t.module].writesIn[r.name] || new Set()).add(s.module);
    }
  }
  if (!has('--outline') && !arg('--deps')) {
    console.log(`${live.length} units, ${stmts.length} top-level statements, ${decl.size} names`);
    if (dups.length) console.log('DECLARED TWICE:\n  ' + dups.join('\n  '));
    for (const m of mods) {
      const I = info[m];
      console.log(`\n${m}: ${(I.bytes / 1024).toFixed(0)} kB, ${I.stmts} statements, ${I.names} names, ${I.exports.size} used elsewhere`);
      for (const [k, v] of Object.entries(I.imports).sort((a, b) => b[1].size - a[1].size)) console.log(`   takes ${String(v.size).padStart(4)} from ${k}`);
      const w = Object.entries(I.writesIn);
      if (w.length) console.log(`   assigned from outside: ` + w.map(([n, s]) => `${n}←${[...s].join('/')}`).join(', '));
    }
    /* Followed through functions: a statement that names a function while it
       runs may call it, so everything that function reads counts too. */
    console.log('\nLOAD-TIME READS ACROSS MODULES (these fix the load order)');
    for (const s of stmts) {
      if (s.declKind === 'function') continue;
      const seen = new Map(), queue = s.refs.filter(r => r.eager).map(r => [r.name, '']);
      while (queue.length) {
        const [n, via] = queue.shift();
        if (seen.has(n)) continue;
        seen.set(n, via);
        const t = decl.get(n);
        if (t.declKind === 'function') for (const r of t.refs) queue.push([r.name, via || n]);
      }
      const out = [...seen].filter(([n]) => decl.get(n).module !== s.module);
      if (out.length > 12) console.log(`  ${s.module}:${s.line} ${s.names[0] || '[' + s.kind + ']'}  reaches ${out.length} names in ${[...new Set(out.map(([n]) => decl.get(n).module))].join(', ')}`);
      else for (const [n, via] of out) console.log(`  ${s.module}:${s.line} ${s.names[0] || '[' + s.kind + ']'}  reads ${n}${via ? ' via ' + via + '()' : ''}  (${decl.get(n).module}, ${decl.get(n).declKind})`);
    }
  }
  if (arg('--json')) {
    const out = { modules: Object.fromEntries(mods.map(m => [m, { bytes: info[m].bytes, statements: info[m].stmts, exports: [...info[m].exports].sort(),
      imports: Object.fromEntries(Object.entries(info[m].imports).map(([k, v]) => [k, [...v].sort()])),
      assignedFromOutside: Object.fromEntries(Object.entries(info[m].writesIn).map(([k, v]) => [k, [...v]])) }])) };
    fs.writeFileSync(arg('--json'), JSON.stringify(out, null, 1) + '\n');
  }
}

if (arg('--move')) move(arg('--move'));
else if (has('--sync')) console.log(`sync: ${sync()} pass(es) wrote changes`);
else if (has('--check')) {
  const r = syncOnce(false);
  if (r) { console.error(`js/ is out of step with itself (${r}) — run module-map.cjs --sync`); process.exit(1); }
  console.log('modules: imports, exports and setters are in step');
} else report();
